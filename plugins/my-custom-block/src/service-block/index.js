function ServiceCard({ card, index, themeColor, onChange }) {
	return (
		<div className="service-card">
			<HandDrawnBorder color={themeColor} />
			<div className="service-card__inner">
				<div className="service-card__header" style={{ color: themeColor }}>
					<span className="service-card__icon">
						{ICONS[card.icon] || ICONS.code}
					</span>
					<RichText
						tagName="h4"
						value={card.title}
						onChange={(val) => onChange(index, "title", val)}
						placeholder={__("Card title…")}
					/>
				</div>
				<ul className="service-card__list">
					{card.items.map((item, i) => (
						<li key={i}>
							<TextControl
								value={item}
								onChange={(val) => {
									const newItems = [...card.items];
									newItems[i] = val;
									onChange(index, "items", newItems);
								}}
							/>
						</li>
					))}
					<li>
						<Button
							variant="tertiary"
							onClick={() => onChange(index, "items", [...card.items, ""])}
						>
							+ {__("Add item")}
						</Button>
					</li>
				</ul>
			</div>
		</div>
	);
}

